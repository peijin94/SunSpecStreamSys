const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright-core');
const assert=require('node:assert/strict');const fs=require('node:fs');
const base=process.env.LWA_TEST_URL||'https://ovsa.njit.edu/live/';
let browser;
(async()=>{
 browser=await chromium.launch({headless:true,executablePath:process.env.BROWSER_EXECUTABLE||undefined});
 const page=await browser.newPage({viewport:{width:1600,height:1100}});const errors=[],spectrumRequests=[];
 page.on('request',r=>{if(/\/spectrum(?:-range)?\?/.test(r.url()))spectrumRequests.push(r.url());});
 page.on('pageerror',e=>errors.push(String(e)));
 await page.goto(base,{waitUntil:'domcontentloaded'});
 const canvas=page.getByTestId('spectrum-canvas-I');
 await page.waitForFunction(()=>Number(document.querySelector('[data-testid="spectrum-canvas-I"]')?.dataset.end)>0);
 const button=page.getByRole('button',{name:'Interactive spectrum measure',exact:true});
 assert.equal(await button.count(),1,'Measurement launcher must exist above live solar images');
 await button.click();
 const panel=page.getByTestId('spectrum-measure-panel');await panel.waitFor();
 await page.waitForFunction(()=>document.querySelector('[data-testid="spectrum-measure-panel"]')?.dataset.ready==='true');
 assert.equal(await page.getByTestId('spectrum-controls').getAttribute('data-playing'),'false');
 const frozenRequests=spectrumRequests.length;
 const frozenEnd=await canvas.getAttribute('data-end');
 await page.waitForTimeout(1700);assert.equal(await canvas.getAttribute('data-end'),frozenEnd);
 assert.ok(await page.getByTestId('spectrum-pause').isDisabled());
 assert.ok(await page.getByTestId('spectrum-live').isDisabled());
 console.log('PASS measurement opens, captures native snapshot, and locks playback');
 const replyPromise=page.waitForResponse(r=>r.url().endsWith('/spectrum-measure')&&r.status()===200);
 const box=await canvas.boundingBox();const pw=box.width-74,ph=box.height-50;
 for(const [x,y] of [[.3,.25],[.5,.45],[.7,.65]])await page.mouse.click(box.x+58+pw*x,box.y+14+ph*y);
 assert.equal(await page.getByTestId('measure-point-count').count(),1,'Point-picking results must exist');
 assert.match(await page.getByTestId('measure-point-count').innerText(),/3 points/);
 await page.waitForFunction(()=>document.querySelectorAll('[data-testid="measure-drift"] circle[data-x]').length===2);
 assert.equal(await page.getByTestId('measure-speed').locator('circle[data-x]').count(),2);
 assert.equal(await canvas.getAttribute('data-measure-count'),'3');
 const reply=await (await replyPromise).json();
 for(const [index,segment] of reply.segments.entries()){
  const drift=page.getByTestId('measure-drift').locator('circle[data-x]').nth(index),speed=page.getByTestId('measure-speed').locator('circle[data-x]').nth(index);
  assert.equal(Number(await drift.getAttribute('data-x')),segment.time);assert.equal(Number(await drift.getAttribute('data-y')),segment.drift_mhz_s);
  assert.equal(Number(await speed.getAttribute('data-x')),segment.r_sun);assert.equal(Number(await speed.getAttribute('data-y')),segment.speed_km_s);
 }
 assert.ok(Number(await page.getByTestId('measure-speed').locator('circle[data-x]').first().getAttribute('data-y'))>0);
 console.log('PASS clicks produce matching drift/time and speed/radius plots through the real API');
 assert.equal(await page.getByRole('button',{name:'Zoom out',exact:true}).count(),1,'Measurement needs explicit zoom-out');
 await page.getByRole('button',{name:'Zoom out',exact:true}).click();
 assert.equal(Number(await canvas.getAttribute('data-end')),Number(frozenEnd));
 assert.equal(await page.getByTestId('spectrum-controls').getAttribute('data-playing'),'false');
 await page.getByText('Select frequency range',{exact:true}).click();
 await page.getByLabel('Minimum frequency MHz').fill('25');await page.getByLabel('Maximum frequency MHz').fill('65');
 await page.getByRole('button',{name:'Apply frequency range',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('[data-testid="spectrum-canvas-I"]')?.dataset.fmin==='25');
 assert.equal(await canvas.getAttribute('data-fmax'),'65');
 assert.match(await page.getByTestId('measure-point-count').innerText(),/3 points/);
 await page.getByTestId('range-3600').click();
 await page.waitForFunction(()=>document.querySelector('[data-testid="spectrum-controls"]')?.dataset.seconds==='3600');
 assert.equal(await canvas.getAttribute('data-end'),frozenEnd);
 console.log('PASS zoom-out, explicit frequency limits and full-hour range preserve frozen measurement');
 const harmonicReply=page.waitForResponse(r=>r.url().endsWith('/spectrum-measure')&&r.request().postDataJSON()?.harmonic===2);
 await page.getByLabel('Emission harmonic').selectOption('2');const harmonicResult=await (await harmonicReply).json();assert.ok(harmonicResult.points[0].r_sun>reply.points[0].r_sun);
 await page.waitForFunction(r=>Number(document.querySelector('[data-testid="measure-speed"] circle')?.getAttribute('data-x'))===r,harmonicResult.segments[0].r_sun);
 assert.equal(spectrumRequests.length,frozenRequests,'Range, frequency and model controls must not fetch live spectra');
 if(process.env.LWA_TEST_OUTPUT){fs.mkdirSync(process.env.LWA_TEST_OUTPUT,{recursive:true});await page.screenshot({path:process.env.LWA_TEST_OUTPUT+'/measure-desktop.png',fullPage:true});}
 await page.getByRole('button',{name:'Undo point',exact:true}).click();assert.match(await page.getByTestId('measure-point-count').innerText(),/2 points/);
 await page.getByRole('button',{name:'Clear points',exact:true}).click();assert.match(await page.getByTestId('measure-point-count').innerText(),/0 points/);assert.equal(await page.getByTestId('measure-speed').locator('circle').count(),0);
 await page.setViewportSize({width:390,height:844});await page.waitForTimeout(250);assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1));
 if(process.env.LWA_TEST_OUTPUT)await page.screenshot({path:process.env.LWA_TEST_OUTPUT+'/measure-mobile.png',fullPage:true});
 console.log('PASS model recalculation, no live fetches, undo/clear and mobile layout');
 await page.getByRole('button',{name:'Close measurement',exact:true}).click();
 assert.equal(await page.getByTestId('spectrum-controls').getAttribute('data-playing'),'false');
 await page.getByTestId('spectrum-pause').click();
 await page.waitForFunction(()=>document.querySelector('[data-testid="spectrum-controls"]')?.dataset.playing==='true');
 assert.deepEqual(errors,[]);console.log('PASS close leaves paused; explicit Play resumes, no browser errors');
 if(process.env.LWA_TEST_OUTPUT){fs.mkdirSync(process.env.LWA_TEST_OUTPUT,{recursive:true});fs.writeFileSync(process.env.LWA_TEST_OUTPUT+'/measure-browser.json',JSON.stringify({base,errors},null,2));}
 await browser.close();
})().catch(async error=>{console.error(error);await browser?.close();process.exitCode=1;});
